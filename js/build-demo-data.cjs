// Run from any directory: node js/build-demo-data.cjs
const fs = require('node:fs');
const path = require('node:path');

const directory = path.join(__dirname, '..', 'json');
const categories = JSON.parse(fs.readFileSync(path.join(directory, 'categories.json'), 'utf8'));
const data = { 'categories.json': categories };
for (const category of categories.categories) {
  const filename = `${category}.json`;
  data[filename] = JSON.parse(fs.readFileSync(path.join(directory, filename), 'utf8'));
}
const serialized = JSON.stringify(data, null, 2).replace(/[\u007f-\uffff]/g,
  character => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);
fs.writeFileSync(path.join(__dirname, 'demo-data.js'),
  `// Generated by build-demo-data.cjs; edit the JSON sources instead.\nwindow.ARCHETYPE_DEMO_DATA = ${serialized};\n`);
